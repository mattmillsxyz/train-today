#!/usr/bin/env node
/**
 * Generates site/exercises.html from the canonical exercise library.
 *
 * The library is the app's content, not the site's, so the public page is
 * generated rather than hand-maintained — there is no second copy to drift.
 * Run it after any change to exercises.json:
 *
 *   node tools/build-site-exercises.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SOURCE = path.join(ROOT, 'ios/DRILL/Resources/exercises.json');
const OUTPUT = path.join(ROOT, 'site/exercises.html');

const TAG_LABELS = {
  warmup: 'Warmup',
  soccer: 'Soccer',
  football: 'Football',
  basketball: 'Basketball',
  baseball: 'Baseball',
  cardio: 'Cardio',
  plyo: 'Plyometrics',
  strength: 'Strength',
  balance: 'Balance',
  track: 'Track',
  stretch: 'Cooldown',
};

// Display order: the shape a session is built in, warmup first, stretch last.
const TAG_ORDER = [
  'warmup', 'soccer', 'football', 'basketball', 'baseball', 'track', 'cardio', 'plyo', 'strength', 'balance',
  'stretch',
];

const ROLE_LABELS = {
  setup: 'Set up',
  form: 'Form',
  cue: 'Tip',
  action: 'Do it',
};

const escape = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const doc = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));

const exercises = [...doc.exercises].sort(
  (a, b) => TAG_ORDER.indexOf(a.tag) - TAG_ORDER.indexOf(b.tag) || a.name.localeCompare(b.name)
);

const usedTags = TAG_ORDER.filter((tag) => exercises.some((e) => e.tag === tag));
const stepCount = exercises.reduce((n, e) => n + e.steps.length, 0);

const filters = [
  '<button class="filter" data-tag="all" aria-pressed="true">All</button>',
  ...usedTags.map(
    (tag) => `<button class="filter" data-tag="${tag}" aria-pressed="false">${escape(TAG_LABELS[tag])}</button>`
  ),
].join('\n      ');

const cards = exercises
  .map((exercise) => {
    const steps = exercise.steps
      .map(
        (step) =>
          `          <li><span class="role role-${step.role}">${escape(ROLE_LABELS[step.role])}</span>${escape(step.text)}</li>`
      )
      .join('\n');
    const pr = exercise.prMetric
      ? `\n        <p class="pr-note">🏆 Tracks a personal record: ${escape(exercise.prMetric.label)}</p>`
      : '';
    return `      <article class="exercise" data-tag="${exercise.tag}">
        <div class="exercise-head">
          <h3>${escape(exercise.name)}</h3>
          <span class="tag tag-${exercise.tag}">${escape(TAG_LABELS[exercise.tag])}</span>
          <span class="duration">${escape(exercise.displayDuration)}</span>
        </div>${pr}
        <ol class="steps">
${steps}
        </ol>
      </article>`;
  })
  .join('\n');

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Every exercise, with full instructions · DRILL</title>
<meta name="description" content="All ${exercises.length} exercises in DRILL, with every step written out: soccer, football, track, cardio, strength, plyometrics and balance drills for 8-12 year olds.">
<meta name="theme-color" content="#0d0d0d">
<link rel="icon" type="image/png" href="favicon.png">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<link rel="stylesheet" href="style.css">
<!-- Generated by tools/build-site-exercises.js from ios/DRILL/Resources/exercises.json. Do not edit by hand. -->
</head>
<body>

<header class="site-header">
  <div class="wrap">
    <a class="brand" href="/"><span class="brand-word" role="img" aria-label="DRILL"></span></a>
    <nav class="site-nav">
      <a href="index.html">Home</a>
      <a href="exercises.html" aria-current="page">Exercises</a>
      <a href="privacy.html">Privacy</a>
      <a href="support.html">Support</a>
    </nav>
  </div>
</header>

<main class="wrap prose" style="max-width:var(--column)">
  <h1>Every exercise, with full instructions</h1>
  <p class="updated">${exercises.length} exercises · ${stepCount} steps · nothing held back</p>
  <p style="margin-top:14px;color:var(--text-secondary)">
    This is the whole library the app draws from, written for an 8&ndash;12 year old to follow
    without a coach standing over them. In the app these steps are timed and read aloud one at a
    time; here they are, all of them, to read before you download anything.
  </p>

  <div class="filter-row">
      ${filters}
  </div>

${cards}
</main>

<footer class="site-footer">
  <div class="wrap">
    <span>&copy; 2026 DRILL</span>
    <nav>
      <a href="index.html">Home</a>
      <a href="privacy.html">Privacy</a>
      <a href="terms.html">Terms</a>
      <a href="support.html">Support</a>
    </nav>
  </div>
</footer>

<script>
  // Filtering is the only script on the site: no framework, no build step.
  const filters = document.querySelectorAll('.filter');
  const cards = document.querySelectorAll('.exercise');
  for (const button of filters) {
    button.addEventListener('click', () => {
      const tag = button.dataset.tag;
      for (const other of filters) {
        other.setAttribute('aria-pressed', String(other === button));
      }
      for (const card of cards) {
        card.hidden = tag !== 'all' && card.dataset.tag !== tag;
      }
    });
  }
</script>

</body>
</html>
`;

fs.writeFileSync(OUTPUT, html);
console.log(
  `Wrote ${path.relative(ROOT, OUTPUT)} — ${exercises.length} exercises, ${stepCount} steps, ${usedTags.length} tags`
);
